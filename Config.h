/**
 * @file Config.h
 * @brief Simulation settings and configuration-file interface.
 */
#ifndef CONFIG_H
#define CONFIG_H

#include <cstdint>
#include <string>
#include <vector>

/**
 * @brief Validated settings used to run one load-balancer simulation.
 */
struct Config {
    /** Default simulation duration when no run-time override is supplied. */
    int simulationCycles = 100;
    /** Number of servers created at startup. */
    int initialServers = 3;
    /** Lowest permitted server-pool size. */
    int minimumServers = 1;
    /** Highest permitted server-pool size. */
    int maximumServers = 10;
    /** Initial FIFO queue fill for each starting server. */
    int initialRequestsPerServer = 100;
    /** Inclusive lower bound for generated request service time. */
    int minimumProcessingTime = 2;
    /** Inclusive upper bound for generated request service time. */
    int maximumProcessingTime = 10;
    /** Queue-per-server scale-up threshold; scaling occurs strictly above it. */
    int scaleUpQueuePerServer = 80;
    /** Queue-per-server scale-down threshold; scaling occurs strictly below it. */
    int scaleDownQueuePerServer = 50;
    /** Minimum number of cycles between successful scaling operations. */
    int scalingCooldownCycles = 10;
    /** Probability of an arrival batch on each cycle, in [0, 1]. */
    double arrivalProbability = 0.65;
    /** Number of requests generated by a successful arrival event. */
    int arrivalBatchSize = 1;
    /** Zero requests a non-deterministic seed; other values repeat a sequence. */
    std::uint32_t randomSeed = 0;
    /** Whether meaningful events are printed and written to the log. */
    bool verbose = true;
    /** Destination path for the simulation log. */
    std::string logFile = "simulation.log";
    /** Exact IPv4 addresses and CIDR ranges rejected before queue admission. */
    std::vector<std::string> blockedIpRanges;

    /**
     * @brief Loads and validates settings from a key-value text file.
     * @param path Configuration file path.
     * @return Parsed settings.
     * @throws std::runtime_error If the file cannot be read or contains invalid settings.
     */
    static Config loadFromFile(const std::string& path);
};

#endif